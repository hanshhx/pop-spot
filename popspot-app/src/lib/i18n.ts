/**
 * 사전 — 로직이 <b>만들어 내는</b> 문구만 담는다.
 *
 * <p>웹의 {@code lib/i18n.tsx} 는 세 언어 사전 전체(2,600줄)와 {@code LocaleProvider} 를 함께 갖는다.
 * 앱은 그중 <b>키의 모양과 {@code t()} 의 계약만</b> 가져온다. 이식한 {@code dday.ts}·{@code stamps.ts}
 * 가 문자열이 아니라 {@link MessageKey} 를 돌려주도록 짜여 있어서, 그 계약을 깨면 두 파일을 앱에서만
 * 다르게 고쳐야 하고 그 순간 웹과의 대조가 불가능해진다.
 *
 * <p><b>화면에 박힌 문구는 아직 여기로 올리지 않았다.</b> 그럴듯해 보이는 선택이지만 지금은 손해다 —
 * 시안이 한국어 한 벌이고, 사전을 거치면 어느 화면의 문구인지 코드에서 사라진다. 사전에 올려야 하는
 * 문구는 <b>로직이 조건에 따라 고르는 것</b>(마감 배지, 스탬프 실패 사유)이고, 그건 화면을 읽어서는
 * 알 수 없으므로 여기 있어야 한다. 레이아웃에 한 번 박히는 문구는 화면에 두는 편이 읽기 쉽다.
 *
 * <p>영어·일본어를 켜는 시점에 {@code DICT} 에 언어를 추가하고, 그때 화면 문구도 함께 옮긴다.
 * 웹이 이미 그 순서를 겪었고, 문구를 먼저 옮겨 둔 덕을 본 적은 없었다.
 */

export type Locale = 'ko';

/**
 * 값이 아니라 <b>키</b>가 계약이다. 웹 사전과 같은 키를 쓰므로, 나중에 앱 문구를 웹에서 가져올 때
 * 이름을 다시 짜지 않아도 된다.
 */
const DICT = {
  ko: {
    /* 마감 배지 — dday.ts 가 고른다. */
    'card.today': '오늘 마감',
    'misc.cardEnded': '종료',

    /* 방문 인증 실패 — stamps.ts 가 서버 400 본문을 보고 고른다. */
    'detail.stampFailed': '이미 인증했거나 처리하지 못했습니다.',
    'detail.stampDailyLimit': '스탬프는 하루 한 곳에서만 인증할 수 있어요. 내일 다시 방문해 주세요.',
    'detail.stampAlreadyDone': '이미 방문 인증을 완료한 팝업이에요.',
  },
} as const;

export type MessageKey = keyof (typeof DICT)['ko'];

/**
 * 키 하나를 지금 언어의 문구로.
 *
 * <p>웹은 이것을 컨텍스트로 내려보낸다 — 언어 상태를 화면 전체가 공유해야 하고, 훅만 두면 컴포넌트마다
 * 별도의 상태가 생겨 한 화면에 두 언어가 섞이기 때문이다. 앱은 아직 언어가 하나뿐이라 그 장치가 할 일이
 * 없어서 함수로 둔다. 언어가 늘어나는 순간 <b>이 파일 안에서</b> 컨텍스트로 바꾸면 되고, 부르는 쪽
 * 서명은 그대로다.
 */
export function t(key: MessageKey, locale: Locale = 'ko'): string {
  return DICT[locale][key];
}
