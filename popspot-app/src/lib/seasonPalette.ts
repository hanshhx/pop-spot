/**
 * 계절별 주 색상 — 라임 스케일을 통째로 갈아끼운다.
 *
 * <p>Tailwind v4 는 유틸리티를 {@code var()} 참조로 뽑는다({@code .bg-lime-300{background-color:
 * var(--color-lime-300)}}). 그래서 {@code globals.css} 에서 계절별로 이 스케일을 덮어쓰면
 * <b>전 페이지 647곳의 라임이 컴포넌트 수정 없이 따라온다</b> — 메인·상세·지도·코스·동행·음악·
 * 여권·SEO 랜딩·관리자까지.
 *
 * <p>이 파일은 그 값의 <b>단일 출처</b>다. CSS 와 어긋나면 {@code seasonPalette.test.ts} 가 잡는다.
 * 값을 고칠 때는 반드시 두 곳을 함께 고쳐야 한다.
 *
 * <h3>어떻게 만든 값인가</h3>
 *
 * <p>손으로 고르면 대비가 무너진다. {@code bg-lime-300 text-ink-900} 조합만 324곳이라,
 * 라임보다 어두운 색을 넣는 순간 앱 전체의 버튼 글자가 안 읽힌다. 그래서 단계마다 <b>역할</b>을
 * 보고 계산으로 뽑았다.
 *
 * <ul>
 *   <li><b>50 · 100 · 200</b> — {@code hover:bg-lime-50} 같은 옅은 바탕. 라임과 <b>같은 휘도</b>로
 *       맞춰 거의 흰색을 유지한다. 여기를 진하게 만들면 은은한 hover 가 색 덩어리가 된다.</li>
 *   <li><b>300 · 400</b> — 주 동작 면. 계절색이 실제로 보이는 곳이라 앵커가 지배한다. 네 계절
 *       모두 잉크 글자 대비 9.7:1 이상으로, AA(4.5) 를 두 배 넘게 넘긴다.</li>
 *   <li><b>500 ~ 900</b> — 글자색. 앵커 휘도를 기준으로 라임의 단계 간 비율을 옮겼다. 결과적으로
 *       <b>대비가 오늘보다 좋아진다</b>(예: 700 을 흰 배경에 얹으면 라임 5.09:1 → 봄 6.57:1).</li>
 * </ul>
 *
 * <p>만채도({@code --s-hi})를 그대로 쓰지 않은 이유가 여기 있다. 겨울 {@code #2f6ea8} 위의 잉크
 * 글자는 3.67:1 로 AA 미달이라, 겨울에만 글자색을 뒤집는 예외를 324곳에 걸어야 한다. 만채도는
 * 로고 SPOT 과 신호 레이어처럼 <b>좁은 면적</b>에만 남긴다.
 */

