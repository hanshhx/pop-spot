-- 관리자 감사 로그에 접속지 정보를 더한다.
--
-- 개인정보보호법은 개인정보처리시스템 접속기록에 "누가 · 언제 · 어떤 정보주체를 · 무슨 업무로"
-- 와 함께 <b>접속지 정보</b>를 남기도록 요구한다. 지금 표에는 앞의 넷은 있는데 접속지만 없었다.
--
-- 그런데 이 서비스는 방문 로그에 IP를 저장하지 않는 것을 방침으로 내세워 왔다. 두 원칙이
-- 부딪히므로, 접속지를 알아볼 수 있을 만큼만 남기고 그 이상은 버린다:
--   IPv4  119.194.113.214 → 119.194.113.0   (마지막 자리 제거)
--   IPv6  앞 네 덩이만
--
-- 해시가 아니라 자르기인 이유는, 해시는 "같은 곳에서 왔는지" 만 알려 주고 "그곳이 어디인지" 는
-- 알려 주지 않기 때문이다. 접속기록의 목적이 "낯선 곳에서 들어왔는가" 를 판단하는 것이라
-- 위치가 남아야 쓸모가 있다.
--
-- NULL 을 허용한다. 이미 쌓인 기록에는 이 값이 없고, 스케줄러가 남기는 기록(사람 접속이 아니다)
-- 에도 없다. NOT NULL 로 두면 기존 행 때문에 마이그레이션이 실패한다.
ALTER TABLE admin_audit_log
    ADD COLUMN IF NOT EXISTS actor_ip VARCHAR(45);

COMMENT ON COLUMN admin_audit_log.actor_ip IS
    '접속지 정보(정밀도 낮춤). IPv4 는 마지막 자리를, IPv6 는 뒷부분을 지운 값.';
