/**
 * 이 주소로 찍은 핀을 <b>정확한 위치</b>로 봐도 되는가.
 *
 * <p>수집한 팝업의 상당수는 주소가 "서울 성수동" 처럼 동네 이름까지만 있다. 지오코더는 그럴 때
 * 그 동네 한복판 좌표를 돌려주는데, 화면에서는 건물 주소로 찍은 핀과 <b>똑같이 생겼다.</b>
 * 2026-08-09 기준 좌표가 있는 919곳 중 402곳이 여기 해당했다.
 *
 * <p>그 핀을 지우면(=안 보여 주면) 지도가 절반으로 줄고, 그대로 두면 "찾아갔는데 없는 곳" 으로
 * 안내하게 된다. 그래서 <b>지우지 않고 다르게 보여 준다</b> — 대략 위치라고 말해 주면 사용자가
 * 그에 맞게 행동한다(동네까지 가서 검색한다).
 *
 * <p>판정은 낱말 단위로 한다. 주소를 이루는 낱말이 <b>전부 행정구역 이름</b>이면 건물을 가리키지
 * 못한다. "성수동" 은 동네고 "더현대 서울" 은 건물이다 — 이 구분이 전부다.
 */

import { REGIONS } from './regions';

/** 행정구역 접미사로 끝나는 낱말 — 성동구·성수동·여의대로 같은 것들. */
const REGION_SUFFIX =
  /^(서울|서울시|서울특별시|경기|경기도|인천|대한민국|한국)$|(특별시|광역시|시|군|구|동|읍|면|리|가|로|길)$/;

/**
 * 접미사가 없는 동네 통칭 — 홍대·강남·이태원처럼 "구" 나 "동" 이 안 붙는 이름들.
 *
 * <p>{@link REGIONS} 를 그대로 쓴다. 여기에 목록을 새로 적으면 동네 칩·필터·랜딩과 갈라져서,
 * 한쪽은 홍대를 동네로 아는데 다른 쪽은 모르는 상태가 된다.
 *
 * <p>다만 {@code keywords} 는 쓰지 않는다 — 거기엔 랜딩 매칭을 위해 '아이파크몰'·'서울숲' 같은
 * <b>건물·시설 이름</b>까지 들어 있어서, 그걸 동네로 세면 "용산 아이파크몰" 이 대략 위치가 된다.
 * 동네 이름 그 자체({@code label})와 상위 행정구역({@code broadKeywords})만 본다.
 */
const REGION_WORDS = new Set(REGIONS.flatMap((r) => [r.label, ...(r.broadKeywords ?? [])]));

/**
 * {@link REGIONS} 에 없는 동네 통칭 — <b>운영 데이터에서 뽑았다</b>(2026-08-09).
 *
 * <p>REGIONS 는 화면에 칩으로 띄우는 12개 상권만 담는다. 그런데 수집된 주소에는 신촌·마곡·북촌처럼
 * 칩에는 없지만 동네 이름인 것이 계속 나온다. 그것들이 "정확한 위치" 로 판정되면 <b>동네 한복판에
 * 정확한 핀인 척</b> 찍힌다.
 *
 * <p>해운대·아오야마·판교는 서울이 아닌데 주소에 "서울" 이 붙어 들어온 것들이다. 좌표가 확실히
 * 틀렸으므로 더더욱 대략으로 봐야 한다.
 *
 * <p>완전한 목록은 만들 수 없다. 빠진 이름이 나오면 여기 더한다 — 틀리는 방향이 "흐리게 보일 것을
 * 또렷하게 보여 준다" 쪽이므로, 발견하는 대로 채우는 것이 맞다.
 */
const EXTRA_AREA_WORDS = new Set([
  '신촌',
  '마곡',
  '영등포',
  '북촌',
  '서촌',
  '광화문',
  '합정',
  '서울숲',
  '반포',
  '건대',
  '연남',
  '판교',
  '해운대',
  '아오야마',
]);

const isRegionWord = (word: string) =>
  REGION_SUFFIX.test(word) || REGION_WORDS.has(word) || EXTRA_AREA_WORDS.has(word);

/** 번지·호수처럼 실제 위치를 좁혀 주는 표시. 이게 있으면 동네 이름만 있는 것이 아니다. */
const HAS_NUMBER = /\d/;

/**
 * 대략 위치(동네 중심점)로 찍혔을 주소인가.
 *
 * @param location 백엔드가 준 원문 주소. 비어 있으면 위치를 모르는 것이므로 대략으로 본다
 */
export function isApproximateLocation(location: string | null | undefined): boolean {
  const text = (location ?? '').replace(/[,()]/g, ' ').trim();
  if (!text) return true;

  // 숫자가 있으면 번지·층·호수 중 하나다. 동네 이름에는 숫자가 안 붙는다.
  if (HAS_NUMBER.test(text)) return false;

  return text.split(/\s+/).every(isRegionWord);
}
