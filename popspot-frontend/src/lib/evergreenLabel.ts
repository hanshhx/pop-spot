/**
 * 검색 결과 제목에 쓸 라벨 — <b>날짜 구간을 뺀다.</b>
 *
 * <p><b>왜.</b> 시점 슬라이스의 라벨에는 날짜가 박혀 있다: {@code 이번 주 (8/31~9/6)},
 * {@code 이번 주말 (9/5)}, {@code 오늘 (9/1 화)}. 화면에서는 그 편이 친절하다 — "이번 주" 가
 * 언제인지 바로 알려 준다.
 *
 * <p>그런데 <b>제목은 검색엔진이 받아 두고 오래 보여 준다.</b> 실측(2026-09-01): 네이버 웹문서
 * 1위인 {@code /popups/hongdae-this-week} 가 라이브에서는 {@code 이번 주 (8/31~9/6) … 20곳}
 * 인데, 네이버 캐시에는 {@code (8/10~8/16) … 22곳} 이 <b>3주째</b> 서 있었다.
 *
 * <p>지난 날짜가 박힌 제목은 클릭을 부르지 않는다. 오히려 "안 고쳐지는 사이트" 라는 신호가 된다.
 * 날짜를 빼면 언제 읽혀도 참이고, 실제 검색어("이번주 홍대 팝업")와도 그대로 맞물린다.
 *
 * <p><b>화면 라벨은 건드리지 않는다.</b> 사용자가 보는 것은 매번 새로 그려지므로 낡을 일이 없다.
 * 낡는 것은 제목뿐이고, 그래서 제목에서만 뺀다.
 *
 * <p>{@code 9월} 처럼 <b>달 이름은 남긴다.</b> 괄호 안 날짜가 아니고, 네이버에서는 오히려
 * 그 형태로 검색한다("성수 9월 팝업 지도" CTR 28.3%).
 */

/**
 * 걷어낼 것 — 괄호 안에 {@code 숫자/숫자} 로 시작하는 덩어리.
 *
 * <p>숫자·슬래시를 요구하는 이유는, 지명이나 브랜드 이름에 들어간 괄호까지 지우지 않기 위해서다
 * (예: {@code 더현대 (여의도)} 는 그대로 둬야 한다).
 */
const DATE_RANGE = /\s*\(\s*\d{1,2}\/\d{1,2}[^)]*\)/g;

export function evergreenLabel(label: string): string {
  return label
    .replace(DATE_RANGE, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
}
