export type MessageKey = keyof (typeof DICT)['ko'];

/**
 * 세 언어가 같은 키를 갖는지 <b>타입 검사 단계에서</b> 확인한다.
 *
 * <p>{@link useLocale}의 t() 는 빠진 키를 한국어로 되돌린다. 화면이 죽지 않는 건 좋지만 누락이
 * 드러나지 않아, 새 문구를 ko 에만 넣고 그대로 배포하기 쉽다. 이 줄이 있으면 tsc 가 먼저 막는다.
 */
const _localeParity: Record<Locale, Record<MessageKey, string>> = DICT;
void _localeParity;

function isLocale(value: string | null): value is Locale {
  return value === 'ko' || value === 'en' || value === 'ja';
}

/**
 * 브라우저 언어에서 시작 언어를 고른다.
 *
 * <p>일본어·영어 사용자만 바꾸고 <b>나머지는 한국어로 둔다.</b> 서비스가 서울 팝업이라 방문자
 * 대부분이 한국인이고, 어중간하게 영어로 넘기면 정작 주 사용자가 불편해진다.
 */
function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'ko';
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const raw of langs) {
    const lang = (raw ?? '').toLowerCase();
    if (lang.startsWith('ko')) return 'ko';
    if (lang.startsWith('ja')) return 'ja';
    if (lang.startsWith('en')) return 'en';
  }
  return 'ko';
}

type LocaleContextValue = {
  locale: Locale;
  setLocale: (next: Locale) => void;
  t: (key: MessageKey) => string;
};

/**
 * 언어 상태는 <b>앱 전체가 하나를 공유해야 한다.</b>
 *
 * <p>처음에는 컨텍스트 없이 훅만 두고 각 컴포넌트가 호출하게 했는데, 훅은 <b>로직을 공유할 뿐 상태를
 * 공유하지 않는다</b> — 호출할 때마다 별도의 useState 가 생긴다. 그래서 홈에서 언어를 바꿔도 랭킹
 * 컴포넌트는 그대로 남아, 화면에 한국어와 일본어가 섞여 나왔다. 타입 검사와 빌드는 모두 통과했고
 * 브라우저에서 실제로 눌러 보고서야 드러났다.
 */
const LocaleContext = createContext<LocaleContextValue | null>(null);

/**
 * 앱 최상단에 한 번 감싼다.
 *
 * <p>첫 렌더는 항상 'ko' 다 — 서버가 만든 HTML 과 다르면 화면이 깜빡이고 hydration 경고가 뜬다.
 * 브라우저에서 한 번 더 그린 뒤에 저장값·브라우저 언어를 반영한다.
 */
export function LocaleProvider({
  children,
  initialLocale,
}: {
  children: ReactNode;
  /**
   * 주소가 언어를 정하는 경우({@code /en}, {@code /ja})에 넘긴다.
   *
   * <p>이 값이 있으면 <b>저장값·브라우저 언어를 보지 않는다.</b> 서버가 그 언어로 HTML 을 그려야
   * 검색엔진이 영어·일본어 페이지로 인식하는데, 브라우저에서 뒤늦게 바꾸면 크롤러가 보는 것은 여전히
   * 한국어다. 주소와 화면 언어가 어긋나면 공유된 링크도 엉뚱한 언어로 열린다.
   */
  initialLocale?: Locale;
}) {
  const pathname = usePathname();
  const [locale, setLocaleState] = useState<Locale>(initialLocale ?? 'ko');

  useEffect(() => {
    if (initialLocale) {
      // 루트 레이아웃은 클라이언트 이동 때 다시 마운트되지 않는다. /en → /ja로 이동해도
      // initialLocale prop은 처음 값일 수 있으므로 현재 주소를 다시 읽어 전역 플레이어·채팅까지 맞춘다.
      const routeLocale: Locale = pathname?.startsWith('/en')
        ? 'en'
        : pathname?.startsWith('/ja')
          ? 'ja'
          : 'ko';
      setLocaleState((current) => (current === routeLocale ? current : routeLocale));
      return;
    }
    const saved = window.localStorage.getItem(STORAGE_KEY);
    setLocaleState(isLocale(saved) ? saved : detectLocale());
  }, [initialLocale, pathname]);

  /**
   * {@code <html lang>} — 스크린리더가 읽는 값이라 화면 언어와 어긋나면 안 된다.
   *
   * <p>v2.49 — <b>Provider 가 겹칠 때 바깥이 이겨 버렸다.</b> {@code /ja} 아래는 루트 Provider 안에
   * 또 하나가 있는데(주소가 언어를 정하는 구조), 화면은 가장 가까운 컨텍스트가 이기지만
   * {@code document.documentElement} 는 <b>둘 다 건드리는 공유 자원</b>이다. 효과는 안쪽부터 도니
   * 나중에 도는 바깥이 덮어써, 화면은 일본어인데 lang 은 "ko" 로 남았다.
   *
   * <p>주소에 언어가 박힌 구간에서는 <b>그 구간의 Provider 에게 맡긴다.</b> 경로를 의존성에 넣어야
   * {@code /ja} 에서 {@code /} 로 돌아올 때도 다시 계산된다 — 안쪽이 사라진 것만으로는 바깥 효과가
   * 다시 돌지 않는다.
   */
  useEffect(() => {
    const routeOwnsLocale = /^\/(en|ja)(\/|$)/.test(pathname ?? '');
    if (!initialLocale && routeOwnsLocale) return;
    document.documentElement.lang = locale;
  }, [locale, initialLocale, pathname]);

  const setLocale = useCallback((next: Locale) => {
    window.localStorage.setItem(STORAGE_KEY, next);
    setLocaleState(next);
  }, []);

  const t = useCallback((key: MessageKey) => DICT[locale][key] ?? DICT.ko[key] ?? key, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

/**
 * 현재 언어와 번역 함수.
 *
 * <p>Provider 밖에서 부르면 한국어로 동작한다 — 언어 하나 때문에 화면이 통째로 죽는 것보다, 기본
 * 언어로라도 보이는 편이 낫다.
 */
export function useLocale(): LocaleContextValue {
  const ctx = useContext(LocaleContext);
  if (ctx) return ctx;
  return {
    locale: 'ko',
    setLocale: () => {},
    t: (key: MessageKey) => DICT.ko[key] ?? key,
  };
}

/**
 * 혼잡도 값은 백엔드가 한국어 문자열로 준다(여유·보통·혼잡·영업중).
 *
 * <p>값 자체를 영어로 바꾸면 이 문자열로 분기하는 곳이 전부 깨진다. 표시할 때만 옮긴다.
 */
export function localizedStatus(status: string | null | undefined, locale: Locale): string {
  if (!status) return '';
  const key = 'status.' + status;
  const dict = DICT[locale] as Record<string, string | undefined>;
  return dict[key] ?? DICT.ko[key as MessageKey] ?? status;
}

