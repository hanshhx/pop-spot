\echo '=== 바꾸기 전 ==='
SELECT popup_id, name, start_date, end_date, category, status
FROM popup_store
WHERE popup_id IN (1199,1736,1855,2691,2167, 1097,967,6206,4226,4225,1391,2809,
                   3033,2362, 1200,4223,5797,1652,2154, 3278,2690,2606,3402)
ORDER BY popup_id;

BEGIN;

-- ── A. 행사 자체가 없다 (합성·유령) ─────────────────────────────────────────
-- 수집 원문을 직접 열어 대조했고, 원문에 그 행사도 날짜도 없었다.
-- 고칠 날짜가 없는 것이 아니라 고칠 행사가 없다.
--
--   1199 "메이플스토리 월드 팝업스토어" — 출처는 게임업계 뉴스 정리글이고, 본문의
--        나열 항목 "메이플스토리 월드 / 웹툰 / 소설 / 굿즈 / 팝업스토어" 에서 두 항목을
--        이어붙여 없는 행사명을 만들었다.
--   1736 "블루보틀 팝업스토어" — 출처는 젝시믹스 성수 입점 기사이고, 블루보틀은
--        "한국 진출 첫 관문으로 성수동을 택하며" 라는 과거 사례 한 문장으로만 나온다.
--   1855 "루 런칭 백화점 팝업" · 2691 "스트레이 키즈 케넥트 성수" · 2167 "신세계 오프프라이스 팝업"
UPDATE popup_store SET status = 'EXPIRED' WHERE popup_id IN (1199, 1736, 1855, 2691, 2167);

-- ── B. 실재하지만 기간 한정 팝업이 아니다 (상설 매장·시설) ──────────────────
-- 날짜만 고치면 "매장을 팝업으로" 노출하게 된다. 그래서 종료일 비우기가 아니라 내림.
--
--   1097 로에베 퍼퓸 — 2026-01-07 오픈한 전 세계 첫 단독 <b>플래그십</b>(상설)
--    967 디올 — 2022-05 오픈한 디올 성수 컨셉 스토어, 4년 넘게 상설 운영
--   6206·4226·4225 캘빈클라인 성수 — 상설 매장 하나가 레코드 셋으로 들어왔다
--   1391 무민 무민공원 — 상설 시설이고 <b>서울도 아니다</b>(경기 의왕).
--        알려진 "서울 접두사" 크롤러 버그의 또 다른 표본이다.
--   2809 로사의 아틀리에
UPDATE popup_store SET status = 'EXPIRED'
WHERE popup_id IN (1097, 967, 6206, 4226, 4225, 1391, 2809);

-- ── C. 결론은 같으나 원문 대조가 미완 ───────────────────────────────────────
-- 12-31 이 거짓이라는 점은 어느 쪽으로 봐도 확실해 지금 내려도 손해가 없다.
-- 3033 은 네이버 블로그 원문 재시도가 남아 있다 — 새 근거가 나오면 되살린다.
--   2362 룰루레몬 — 기간이 1,095일(3년)로 적혀 있었다.
UPDATE popup_store SET status = 'EXPIRED' WHERE popup_id IN (3033, 2362);

-- ── D. 실제 기간이 확정된 것 — 날짜를 고친다 ────────────────────────────────
-- 공식 보도자료·복수 매체 대조로 확정. 1652 만 수정 후에도 진행 중으로 남는다(9/25까지).

-- 1200 메이플스토리 잠실 — 넥슨 23주년 '메이플 어택! with 롯데', 롯데월드몰 1층 아트리움
UPDATE popup_store SET start_date = '2026-05-22', end_date = '2026-06-14' WHERE popup_id = 1200;

-- 4223 구찌 에디터룸
UPDATE popup_store SET start_date = '2026-07-30', end_date = '2026-08-09' WHERE popup_id = 4223;

-- 5797 전지적 독자 시점 콜라보 카페
UPDATE popup_store SET start_date = '2026-07-31', end_date = '2026-08-17' WHERE popup_id = 5797;

-- 1652 에픽세븐·카제나 — 마리오아울렛 1관 5층. 공식 보도자료로 확정.
UPDATE popup_store SET start_date = '2026-06-26', end_date = '2026-09-25' WHERE popup_id = 1652;

-- 2154 귀멸의 칼날 무한성편 — AK PLAZA 홍대 4층 LIMITION.
--      주소는 채우지 않는다. 홍대(서울)와 수원 중 어느 쪽이 원본인지 확정되지 않았고,
--      기간은 두 곳이 같아 날짜 수정에는 영향이 없다.
UPDATE popup_store SET start_date = '2026-07-07', end_date = '2026-08-02' WHERE popup_id = 2154;

\echo '=== 바꾼 뒤 ==='
SELECT popup_id, name, start_date, end_date, category, status
