-- 사람 판단 4건 — 2026-09-07 (3차, 마지막)
--
-- 1·2차에서 "자동으로 하지 않고 남겨 둔" 것들이다. 셋 다 SQL 이 어려워서가 아니라
-- <b>사실만으로 답이 나오지 않아서</b> 미뤘다. 이번에 운영자가 판단했다.
--
-- 결정 요약: hide 3건 + 시작일 수정 1건 = 4건.
--
-- 안전장치는 1·2차와 같다.
--   파일 끝이 ROLLBACK 이다. 적용하려면 그 한 줄을 COMMIT 으로 바꾼다.
--   페이저는 파일이 스스로 끈다. 그래도 psql 이 tty 를 보고 페이저를 켜면
--   호출할 때 `| cat` 을 붙인다 — 1차 때 여기서 네 번 걸렸고, 마지막에 통한 것이 그것이다.

\set ON_ERROR_STOP on
\pset pager off
\timing off

\echo '=== 바꾸기 전 ==='
SELECT popup_id, name, start_date, end_date, category, status
FROM popup_store
WHERE popup_id IN (2606, 2690, 3278, 3402, 1652, 3493)
ORDER BY popup_id;

BEGIN;

-- ── 2606 세가 미니 뮤지엄 — 장소가 이미 다른 팝업 것이다 ────────────────────
-- 종료일 2026-12-31 에 근거가 없다. 그리고 결정적인 것은 장소다 —
-- 같은 자리(마리오아울렛 1관 5층)를 1652 에픽세븐·카제나가 6/26~9/25 로 점유하고 있고,
-- 오늘(09-07) 기준 진행 중이다. 한 공간이 한 번에 한 팝업만 받는다면 세가는 6/26 이전에 끝났다.
--
-- 나머지 두 선택지가 왜 나쁜가를 적어 둔다. 12-31 을 그냥 두면 거짓이 남고,
-- NULL 로 두면 <b>끝난 팝업이 무기한 진행 중</b>이 된다 — 공개 조회가
-- end_date IS NULL 을 통과시키므로 스스로 만료되지 않기 때문이다.
--
-- ⚠️ 확인하지 못한 것: 그 층이 한 번에 한 팝업만 받는지는 모른다. 추론이다.
--    그래서 지우지 않고 내린다 — 되살리려면 status 를 되돌리는 UPDATE 한 줄이면 된다.
UPDATE popup_store SET status = 'EXPIRED' WHERE popup_id = 2606;

-- ── 2690 토리든 — 우리가 아는 것은 매장 종료일이 아니다 ──────────────────────
-- 22건 중 유일하게 공식 자료가 12/31 을 적은 건이었다. 그런데 그 값은 자사몰 게시판의
-- "이벤트기간 2026.07.15 00:00 ~ 2026.12.31 23:59" 로, <b>분·초가 붙은 온라인 프로모션 서식</b>
-- 이지 매장 운영 종료일의 서식이 아니다. 즉 확인된 사실은 "온라인 이벤트가 12/31 까지" 뿐이고
-- 매장이 언제 닫는지는 여전히 모른다.
--
-- 기간이 5.5개월이라 2026-09-07 에 배포한 크롤러 규칙("6개월을 넘으면 팝업인지 의심")의
-- 바로 아래다. 규칙이 자동으로 걸러 주지 않는 구간이므로 사람이 정했다.
--
-- 부수로 드러난 것 둘 — 살리기로 했다면 함께 고쳐야 했을 것들이다.
--   · 분야가 FASHION 인데 토리든은 스킨케어 브랜드다(BEAUTY 가 맞다).
--   · 이름이 "토리든 팝업 26.07.15(수) - 12. 31(목)" 이다. 크롤러가 날짜를 이름에 넣었다.
--     내리는 쪽으로 정했으므로 이번에는 고치지 않지만, 이름에 기간이 들어가는 것은
--     이 레코드만의 문제가 아닐 수 있다 — 별도로 볼 것.
UPDATE popup_store SET status = 'EXPIRED' WHERE popup_id = 2690;

-- ── 3278 네이버웹툰 팝업스토어 — 3402 와 같은 행사다 ─────────────────────────
-- 같은 캠페인, 같은 장소(용산 아이파크몰)인데 3278 은 시작일조차 없다.
-- 본문도 서로를 가리킨다 — 3278 "첫 장소로 용산 아이파크몰을 선택했다",
-- 3402 "올해 12월까지 이어지는 릴레이 팝업".
--
-- 2차에서 "3278 만 내리면 안 된다" 고 적었던 이유는, 한쪽만 손대면 남은 쪽이 근거 없는
-- 종료일을 그대로 들고 대표가 되기 때문이었다. 이번에 둘을 함께 결재하므로 그 조건이 풀렸다.
UPDATE popup_store SET status = 'EXPIRED' WHERE popup_id = 3278;

-- ── 3402 네이버웹툰 인기 IP 릴레이 — 시작일만 고친다 ────────────────────────
-- 공식 보도자료 기준 08-01 인데 08-04 로 적혀 있다.
--
-- <b>종료일 12-31 은 일부러 그대로 둔다.</b> 이 12-31 은 다른 12-31 들과 성격이 다르다 —
-- 보도자료가 "올해 12월까지" 라고 했으므로 <b>상한선으로는 근거가 있다.</b>
-- NULL 로 바꾸면 화면은 "마감일 미정" 으로 그리지만 공개 조회가 end_date IS NULL 을
-- 통과시켜 <b>스스로 만료되지 않는다.</b> 근거 있는 근사값을 버리고 영구 노출을 얻는 맞바꿈이라
-- 하지 않는다.
UPDATE popup_store SET start_date = '2026-08-01' WHERE popup_id = 3402;

\echo '=== 바꾼 뒤 ==='
SELECT popup_id, name, start_date, end_date, category, status
FROM popup_store
WHERE popup_id IN (2606, 2690, 3278, 3402, 1652, 3493)
ORDER BY popup_id;

-- 시험 실행은 여기서 되돌린다. 적용할 때 이 줄을 COMMIT 으로 바꾼다.
ROLLBACK;

-- ── 대조용으로 함께 조회하는 둘 (건드리지 않음) ─────────────────────────────
--
-- 1652 에픽세븐·카제나 — 2606 판단의 근거다. 6/26~9/25 로 진행 중이어야 한다.
--   이 값이 표에서 다르게 나오면 2606 을 내리는 근거가 무너지므로, 실행 전에 눈으로 본다.
--
-- 3493 원피스 무기와라스토어 — 이번 4건에 없지만 같은 모양의 결정이 남아 있다.
--   3402 와 달리 <b>종료 고지 자체가 없어</b> 12-31 에 근거가 전혀 없다.
--   3402 를 유지하기로 한 논리(보도자료 상한선)가 여기엔 적용되지 않는다. 다음에 결정할 것.
