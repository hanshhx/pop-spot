-- 팝업 날짜 교정 — 2026-09-06
--
-- 근거: 후보 12곳을 공개·공식 자료로 대조한 검증(마스터 플랜 §7.4).
--       각 항목의 출처 URL 은 그 검증 보고에 있다.
--
-- 성격: 이 파일은 "운영 자료를 바꾸는 제안" 이다. 웹 조사 결과이므로
--       실행 전에 사람이 표를 읽고 판단한다. 특히 1003 은 손대지 않는다 —
--       "못 찾음" 이지 "없음" 이 아니다.
--
-- 안전장치:
--   · 지우지 않는다. 날짜를 고치거나 status='EXPIRED' 로 내린다.
--   · status 를 되돌리는 코드는 저장소에 없다(EXPIRED 를 쓰는 쿼리는 한 곳뿐).
--     즉 숨김은 한 방향이고, 되살리려면 사람이 다시 UPDATE 해야 한다.
--   · 끝난 날짜로 고치면 공개 조회가 이미 걸러낸다
--     (PopupStoreRepository: end_date IS NULL OR end_date >= :today).
--     그래서 날짜만 고쳐도 목록에서 사라진다 — status 를 따로 건드릴 필요가 없다.
--
-- 컬럼 확인함(PopupStore 엔티티): 테이블 popup_store, PK popup_id(=id 아님),
--   start_date/end_date 는 varchar, status, category, content.

\set ON_ERROR_STOP on

-- 페이저를 끈다. 켜져 있으면 첫 SELECT 결과에서 less 가 입력을 기다리며 멈추고,
-- 그 뒤의 UPDATE 는 실행되지 않는다. 2026-09-06 에 실제로 그렇게 됐다 — 화면에는
-- 표가 두 번 찍혀 "바꿨는데 안 바뀐" 것처럼 보였지만, 사실은 아무것도 실행되지
-- 않았다. 호출할 때 -P pager=off 를 붙이는 것에 기대지 않고 파일이 스스로 끈다.
\pset pager off

-- 각 문장이 무엇을 했는지 보이게 한다. UPDATE 가 0행을 맞춰도 조용히 지나가면
-- 안 된다 — 이 작업에서 알아야 할 것이 바로 "몇 행이 바뀌었나" 다.
\timing off

-- ── 바꾸기 전 ────────────────────────────────────────────────────────────────
\echo '=== 바꾸기 전 ==='
SELECT popup_id, name, start_date, end_date, category, status
FROM popup_store
WHERE popup_id IN (3706, 2405, 3767, 3034, 4611, 2826, 2796, 2320, 1003, 3402, 3493)
ORDER BY popup_id;

BEGIN;

-- ── A. 연도 오타 — 고치면 "지금 진행 중" 으로 뜬다 ──────────────────────────
-- 3706 김해김 10주년 아카이빙 상품 팝업
--   기록 2027-09-02~2027-09-20 → 실제 2026-09-02~2026-09-20.
--   1년 뒤로 적혀 있어서 지금 열려 있는데도 목록에 안 뜬다.
--   분야도 FOOD 로 되어 있으나 김해김은 디자이너 김인태의 패션 브랜드다.
UPDATE popup_store
SET start_date = '2026-09-02', end_date = '2026-09-20', category = 'FASHION'
WHERE popup_id = 3706;

-- ── B. 이미 끝난 행사 — 실제 기간으로 되돌린다 ──────────────────────────────
-- 2405 노브랜드 버거 X 카스 제로
--   기록 2026-08-23~2026-10-23 → 실제 2026-07-23~2026-08-23.
--   종료일이 시작일 칸에 들어갔다(성수랩점·코엑스점 두 회차가 한 줄로 뭉치며 생긴 일).
--   신세계푸드 공식 보도자료 기준.
UPDATE popup_store
SET start_date = '2026-07-23', end_date = '2026-08-23'
WHERE popup_id = 2405;

-- 3767 포켓몬 팝업스토어
--   기록 2026-08-20~2026-12-31 → 실제 2026-08-16~2026-08-31.
--   12-31 은 "달 단위 표현을 날짜로 바꾼" 값이다.
UPDATE popup_store
SET start_date = '2026-08-16', end_date = '2026-08-31'
WHERE popup_id = 3767;

-- 3034 아벡쉐리
--   기록 2026-01-01~2026-12-31 → 실제 2026-02-06~2026-04-23.
--   01-01~12-31 은 1년 통짜 플레이스홀더다.
UPDATE popup_store
SET start_date = '2026-02-06', end_date = '2026-04-23'
WHERE popup_id = 3034;

-- 4611 용산 해리포터 마호도코로
--   기록 2026-08-15~2026-10-11 → 실제 2025-06-26~2025-08-24. 1년 전에 끝났다.
--   대원미디어(국내 공식 운영사) 공식 페이스북 공지 기준.
UPDATE popup_store
SET start_date = '2025-06-26', end_date = '2025-08-24'
WHERE popup_id = 4611;

-- ── C. 레코드 자체가 틀렸다 — 내린다 ────────────────────────────────────────
-- 2826 "스포티지 팝업 스토어"
--   이름은 기아 스포티지, 본문은 혼다 CR-V. 기록대로의 행사는 공개 자료에 없다.
--   본문이 가리키는 실재 행사는 2025-11 스타필드 하남·타임빌라스 수원의 혼다 행사로,
--   장소(성수동 언더스탠드에비뉴)도 연도도 다르다.
UPDATE popup_store SET status = 'EXPIRED' WHERE popup_id = 2826;

-- 2796 널디 플래그십
--   2024-04-09~2026-11-16. 2년 반짜리는 팝업이 아니라 상설 플래그십 매장이다.
UPDATE popup_store SET status = 'EXPIRED' WHERE popup_id = 2796;

-- 2320 TSUTAYA IP 서점 블루 아카이브
--   국내 행사가 아니다. 시부야·오사카·교토·후쿠오카 TSUTAYA 의 일정을 그대로 가져왔다.
--   기간이 우리 기록과 "일치" 하는 유일한 레코드였는데, 그 일치가 일본 회기와의 일치였다.
UPDATE popup_store SET status = 'EXPIRED' WHERE popup_id = 2320;

-- ── 바꾼 뒤 ─────────────────────────────────────────────────────────────────
\echo '=== 바꾼 뒤 ==='
SELECT popup_id, name, start_date, end_date, category, status
FROM popup_store
WHERE popup_id IN (3706, 2405, 3767, 3034, 4611, 2826, 2796, 2320, 1003, 3402, 3493)
ORDER BY popup_id;

-- 시험 실행은 여기서 되돌린다. 실제로 적용할 때 이 줄을 COMMIT 으로 바꾼다.
ROLLBACK;

-- ── 손대지 않는 것 ──────────────────────────────────────────────────────────
--
-- 1003 "더 퍼스트 슬램덩크"
--   2026년 팝업의 근거를 찾지 못했다(그 기간 더현대 자리는 스파이더맨·산리오·
--   레이디 디올이 차지했다는 자료는 있다). 그러나 "못 찾음" 은 "없음" 이 아니다.
--   사람이 확인한 뒤 결정한다.
--
-- 3402 네이버웹툰 릴레이 / 3493 원피스 무기와라스토어
--   둘 다 end_date 가 2026-12-31 인데 공식 고지가 아니다.
--   3402 는 보도자료의 "올해 12월까지" 를 날짜로 바꾼 것이라 상한선으로는 말이 된다.
--   3493 은 종료 고지 자체가 없어 12-31 에 근거가 없다.
--
--   NULL 로 두면 화면이 "마감일 미정" 으로 그린다(savedPeriodBadge). 다만 공개 조회가
--   end_date IS NULL 을 통과시키므로 그 팝업은 스스로 만료되지 않는다 — 사람이 내려야 한다.
--   틀린 날짜를 없애는 대신 영구 노출을 얻는 맞바꿈이라, 자동으로 하지 않고 남겨 둔다.
--
--   적용하려면:
--     UPDATE popup_store SET end_date = NULL WHERE popup_id IN (3493);        -- 근거 없음
--     UPDATE popup_store SET end_date = NULL WHERE popup_id IN (3402, 3493);  -- 둘 다
--
-- 3034 의 본문
--   "매일 10시 30분부터 22시까지 영업" 은 이 회차의 정보가 아니다(롯데월드몰 회차의
--   운영시간과 일치한다). 근거 없는 문장이므로 지우는 것이 맞지만, 본문을 어떻게 다시
--   쓸지는 사람이 정한다.
