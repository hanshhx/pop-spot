-- 3493 원피스 무기와라스토어 — 2026-09-07 (4차)
--
-- 1·2차에서 판단을 미룬 마지막 한 건이다. 3차(사람 판단 4건)에도 넣지 않았는데,
-- 그때 계획서가 이렇게 적고 있었기 때문이다 — "3402 와 달리 종료 고지 자체가 없어
-- 12-31 에 근거가 전혀 없다."
--
-- 이번에 공개 자료를 직접 열어 확인했다(조사 3각도 + 반증 3회). 결론은 둘이다.
--   1. 기간 한정 팝업이 맞다. 상설 매장이 아니다.
--   2. 종료일은 공표된 적이 없다. 12-31 은 어떤 출처도 없는 값이다.
--
-- 그래서 내리지 않고 <b>종료일만 비운다.</b>
--
-- 안전장치는 1~3차와 같다. 파일 끝이 ROLLBACK 이다. 적용하려면 그 한 줄을 COMMIT 으로
-- 바꾼다. 페이저는 파일이 스스로 끈다(1차 때 여기서 네 번 걸렸다).

\set ON_ERROR_STOP on
\pset pager off
\timing off

\echo '=== 바꾸기 전 ==='
SELECT popup_id, name, start_date, end_date, category, status
FROM popup_store
WHERE popup_id IN (3493, 3402)
ORDER BY popup_id;

BEGIN;

-- ── 종료일을 비운다 ─────────────────────────────────────────────────────────
-- 공식 어디에도 「まで」·「~까지」가 없다. 일본 공식(one-piece.com/news/80782,
-- mugiwara-store.com/store/2555/), 한국 공식 인스타그램(@mugiwarastorekr),
-- 국내 언론 6~8곳이 전부 "2026年7月30日(木)～" / "2026.07.30 GRAND OPEN" 에서 끝난다.
--
-- <b>status='EXPIRED' 로 내리지 않는 이유.</b> EXPIRED 는 "이미 끝났다" 는 사실 주장인데
-- 끝났다는 증거가 하나도 없다. 그러면 12-31 과 똑같이 근거 없는 값을 새로 쓰는 셈이다.
--
-- <b>상설 매장이 아닌 이유.</b> 공식 점포 목록이 常設店(일본 11곳)과 出張店을 구조적으로
-- 나눠 두었고 한국은 出張店 칸이다. 운영사 공식 뉴스가 「期間限定で…オープンします」라고
-- 스스로 못박고, 한국 공식 명칭도 '한국 출장점' 이다. 즉 로에베 플래그십·캘빈클라인
-- 성수처럼 "애초에 팝업이 아닌 것" 유형이 아니다.
--
-- <b>그리고 열린 「～」 표기가 상설을 뜻하지 않는다는 실례가 있다.</b> 완전히 같은 표기의
-- 싱가포르 出張店(2025年9月12日～)이 2026-08-31 에 폐점했다. 「～」는 '종료일 미고지' 다.
UPDATE popup_store SET end_date = NULL WHERE popup_id = 3493;

-- ── 분야를 고친다 ───────────────────────────────────────────────────────────
-- 원피스 애니메이션 IP 의 공식 굿즈숍이다(국내 운영 대원미디어). 옷을 파는 곳이 아니다.
-- CHARACTER 는 운영에서 298건이 쓰는 실재 값이다.
UPDATE popup_store SET category = 'CHARACTER' WHERE popup_id = 3493;

\echo '=== 바꾼 뒤 ==='
SELECT popup_id, name, start_date, end_date, category, status
FROM popup_store
WHERE popup_id IN (3493, 3402)
ORDER BY popup_id;

-- 시험 실행은 여기서 되돌린다. 적용할 때 이 줄을 COMMIT 으로 바꾼다.
ROLLBACK;

-- ── 함께 조회하는 3402 (건드리지 않음) ──────────────────────────────────────
-- 3차에서 12-31 을 <b>유지</b>하기로 한 건이다. 두 건을 다르게 다루는 근거를 표에서
-- 나란히 보라는 뜻이다.
--   3402 는 보도자료가 "올해 12월까지" 라고 적었다 → 12-31 이 상한선으로 근거가 있다.
--   3493 은 그런 문장이 어디에도 없다 → 12-31 이 근거가 0 이다.
-- 겉보기에 같은 값이지만 하나는 근사값이고 하나는 날조다.

-- ── ⚠️ 이 조치가 미루는 문제 ────────────────────────────────────────────────
-- end_date 가 NULL 이면 공개 조회를 그대로 통과한다(PopupStoreRepository 의
-- "endDate IS NULL OR endDate = '' OR endDate >= :today"). 즉 이 레코드는 <b>스스로
-- 만료되지 않는다.</b> 싱가포르 선례상 1년 안팎에 조용히 닫힐 텐데, 사람이 내리지 않으면
-- 폐점 후에도 계속 노출된다.
--
-- <b>재확인을 걸지 않으면 이 조치는 문제를 해결한 것이 아니라 미룬 것이다.</b>
-- 확인할 곳: 공식 인스타그램 @mugiwarastorekr · mugiwara-store.com/store/2555/ ·
-- 롯데월드 어드벤처 기프트샵 목록. 지금은 셋 다 열지 못했다(JS 렌더링·HTTP 402).

